"""
LLM-as-Judge for reply quality evaluation.

Evaluates generated replies on 5 dimensions:
1. Relevance — does the reply address the customer's issue?
2. Tone — does it match the brand's voice?
3. Accuracy — is it factually correct?
4. Helpfulness — does it provide actionable next steps?
5. Completeness — is anything missing?

Each dimension scored 1-5 with free-text rationale.
"""

import sys
import json
from pathlib import Path

from tqdm import tqdm

sys.path.insert(0, str(Path(__file__).parent.parent))
from config import MODEL_JUDGE, BRAND_NAME, JUDGE_DIMENSIONS
from llm import chat_completion_json


def judge_reply(customer_message, generated_reply, actual_reply=None, intent=None):
    """
    Use LLM-as-judge to evaluate a generated reply.

    Args:
        customer_message: The original customer message.
        generated_reply: The AI-generated reply.
        actual_reply: The actual brand reply (optional, for reference).
        intent: The classified intent (optional).

    Returns:
        dict with dimension scores and rationales.
    """
    reference_text = ""
    if actual_reply:
        reference_text = f'\nReference reply (what the brand actually said): "{actual_reply}"'

    intent_text = f"\nDetected intent: {intent}" if intent else ""

    prompt = f"""You are evaluating a customer support reply generated by an AI agent for {BRAND_NAME}.

Customer message: "{customer_message}"{intent_text}

AI-generated reply: "{generated_reply}"{reference_text}

Rate the AI-generated reply on each dimension from 1 (terrible) to 5 (excellent):

1. **Relevance**: Does the reply directly address the customer's specific issue?
   1=completely irrelevant, 3=partially relevant, 5=perfectly addresses the issue

2. **Tone**: Does it match {BRAND_NAME}'s professional, helpful brand voice?
   1=rude/robotic, 3=acceptable but generic, 5=perfectly on-brand

3. **Accuracy**: Is the information factually correct? Does it avoid hallucinations?
   1=factually wrong, 3=mostly correct with minor issues, 5=completely accurate

4. **Helpfulness**: Does it provide actionable next steps or a clear path to resolution?
   1=no useful guidance, 3=some guidance, 5=clear actionable steps

5. **Completeness**: Does the reply cover everything the customer needs?
   1=major gaps, 3=covers basics, 5=thorough and complete

Respond in JSON format:
{{
    "relevance": {{"score": 4, "rationale": "..."}},
    "tone": {{"score": 5, "rationale": "..."}},
    "accuracy": {{"score": 3, "rationale": "..."}},
    "helpfulness": {{"score": 4, "rationale": "..."}},
    "completeness": {{"score": 4, "rationale": "..."}},
    "overall_score": 4.0,
    "overall_rationale": "Brief overall assessment"
}}"""

    result = chat_completion_json(
        messages=[
            {"role": "system", "content": f"You are an expert evaluator of customer support quality for {BRAND_NAME}. Be critical but fair. Respond only with valid JSON."},
            {"role": "user", "content": prompt},
        ],
        model=MODEL_JUDGE,
        temperature=0.2,
        max_tokens=1024,
    )

    # Extract scores
    scores = {}
    for dim in JUDGE_DIMENSIONS:
        dim_data = result.get(dim, {})
        if isinstance(dim_data, dict):
            scores[dim] = {
                'score': int(dim_data.get('score', 3)),
                'rationale': dim_data.get('rationale', ''),
            }
        else:
            scores[dim] = {'score': int(dim_data) if dim_data else 3, 'rationale': ''}

    # Overall score
    dimension_scores = [scores[d]['score'] for d in JUDGE_DIMENSIONS]
    scores['overall_score'] = sum(dimension_scores) / len(dimension_scores)
    scores['overall_rationale'] = result.get('overall_rationale', '')

    return scores


def judge_batch(evaluation_data, show_progress=True):
    """
    Judge a batch of replies.

    Args:
        evaluation_data: List of dicts with 'customer_message', 'generated_reply',
                        optional 'actual_reply', optional 'intent'.
        show_progress: Show progress bar.

    Returns:
        List of judgment dicts.
    """
    results = []
    iterator = tqdm(evaluation_data, desc="Judging replies") if show_progress else evaluation_data

    for item in iterator:
        try:
            judgment = judge_reply(
                customer_message=item['customer_message'],
                generated_reply=item['generated_reply'],
                actual_reply=item.get('actual_reply'),
                intent=item.get('intent'),
            )
            judgment['customer_message'] = item['customer_message']
            judgment['generated_reply'] = item['generated_reply']
            results.append(judgment)
        except Exception as e:
            print(f"\n  [!] Error judging reply: {str(e)[:100]}")
            results.append({
                'customer_message': item['customer_message'],
                'generated_reply': item['generated_reply'],
                'error': str(e),
                'overall_score': 0,
            })

    return results


def summarize_judgments(judgments):
    """Compute aggregate statistics from judgment results."""
    valid = [j for j in judgments if 'error' not in j]

    if not valid:
        return {'error': 'No valid judgments'}

    summary = {}
    for dim in JUDGE_DIMENSIONS:
        scores = [j[dim]['score'] for j in valid if dim in j]
        if scores:
            summary[dim] = {
                'mean': sum(scores) / len(scores),
                'min': min(scores),
                'max': max(scores),
                'std': (sum((s - sum(scores)/len(scores))**2 for s in scores) / len(scores)) ** 0.5,
            }

    overall_scores = [j['overall_score'] for j in valid]
    summary['overall'] = {
        'mean': sum(overall_scores) / len(overall_scores),
        'min': min(overall_scores),
        'max': max(overall_scores),
        'n_evaluated': len(valid),
        'n_errors': len(judgments) - len(valid),
    }

    return summary


def print_judge_summary(summary):
    """Print a formatted summary of LLM judge results."""
    print("\n[JUDGE] LLM Judge Evaluation:")
    print(f"   Evaluated: {summary['overall']['n_evaluated']} replies")

    for dim in JUDGE_DIMENSIONS:
        if dim in summary:
            s = summary[dim]
            print(f"   {dim:15s}: {s['mean']:.2f} ± {s['std']:.2f} "
                  f"(range: {s['min']}-{s['max']})")

    print(f"\n   Overall Score: {summary['overall']['mean']:.2f} / 5.00")
